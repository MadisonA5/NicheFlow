-- This program creates the listing_blackouts table for BO-01. A
-- supplier marks a UTC window on their own listing as unavailable,
-- separate from the bookings lifecycle, so a booking create can
-- reject a window that falls inside one, and the availability
-- endpoint can shade it on the calendar the same way a reserved
-- booking is shaded.
--
-- File:   V8__create_listing_blackouts_table.sql
-- Course: AUCSC 325
--
-- References:
-- https://www.postgresql.org/docs/current/ddl-constraints.html#DDL-CONSTRAINTS-EXCLUSION
--     - Exclusion constraints
-- https://www.postgresql.org/docs/current/rangetypes.html
--     - tstzrange and the overlap operator
--

CREATE TABLE listing_blackouts (
    -- To identify each blackout; generated by the database
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    -- To point at the listing the supplier is blacking out
    listing_id  BIGINT NOT NULL,
    -- To store the blackout start in UTC
    start_time  TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- To store the blackout end in UTC
    end_time    TIMESTAMP(6) WITH TIME ZONE NOT NULL,
    -- To let the supplier note why, e.g. "Vacation"
    reason      VARCHAR(255),
    -- To record when the supplier added this blackout
    created_at  TIMESTAMP(6) WITH TIME ZONE NOT NULL DEFAULT now(),
    -- To reject a slot that ends at or before it starts
    CONSTRAINT ck_listing_blackouts_end_after_start
        CHECK (end_time > start_time),
    -- To keep a blackout only when its listing still exists
    CONSTRAINT fk_listing_blackouts_listing
        FOREIGN KEY (listing_id) REFERENCES listings (id)
);

-- To look up the blackouts on a listing
CREATE INDEX idx_listing_blackouts_listing_id
    ON listing_blackouts (listing_id);

-- To compare listing equality and time overlap in one GiST index.
-- btree_gist was already created by V4, but this stays
-- self-contained in case migrations are ever replayed independently.
CREATE EXTENSION IF NOT EXISTS btree_gist;

-- To reject a second blackout on the same listing whose window
-- overlaps one already stored. A blackout that starts when another
-- ends is allowed.
ALTER TABLE listing_blackouts
    ADD CONSTRAINT ex_listing_blackouts_listing_window
    EXCLUDE USING gist (
        listing_id WITH =,
        tstzrange(start_time, end_time, '[)') WITH &&
    );
